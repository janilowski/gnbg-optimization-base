# Summary: This algorithm, named GNBG (Guess-and-Check for Numerical Black-box Global), employs a hybrid strategy combining initial broad exploration with an iterative cycle of exploitation and controlled exploration. It starts by sampling a few points uniformly across the search space to establish an initial best candidate. In the main loop, it primarily attempts to improve the current best solution by perturbing it with Gaussian noise (exploitation). Periodically, it introduces fully uniform random samples (exploration) to mitigate premature convergence and discover new promising regions. All candidate solutions are evaluated against the current budget and clipped to stay within problem bounds.
# Search state: The algorithm maintains the `best_x` (the candidate input vector that yielded the lowest objective value found so far) and `best_y` (its corresponding objective value). It also tracks `current_budget_used` to ensure the total budget is not exceeded.
# Candidate generation: Candidates are generated using two primary mechanisms:
# 1. Uniform Exploration: A new candidate `x` is drawn from a uniform distribution across the entire search space, `U(lower_bound, upper_bound)`.
# 2. Incumbent-Centered Perturbation (Exploitation): A new candidate `x'` is generated by adding Gaussian noise to the current `best_x`. The standard deviation of this noise is a fixed fraction (`perturbation_scale_factor`) of the total range of each dimension. `x' = best_x + N(0, perturbation_scale_factor * (upper_bound - lower_bound))`.
# Selection and replacement: A greedy selection strategy is used. Any newly generated and evaluated candidate `x_candidate` replaces the current `best_x` if its objective value `y_candidate` is strictly lower than `best_y`. Otherwise, the incumbent `best_x` is retained.
# Adaptation: The algorithm does not feature explicit adaptation mechanisms for its parameters (e.g., `exploration_probability` or `perturbation_scale_factor`). These parameters remain constant throughout the optimization process. However, the search implicitly adapts by narrowing its exploitation focus around a progressively better `best_x` as the optimization proceeds.
# Exploration mechanisms:
# 1. Initial Random Sampling: A small number of points are sampled uniformly at the very beginning to quickly cover the search space and find an initial good starting point.
# 2. Periodic Uniform Exploration: During the main loop, with a fixed `exploration_probability`, the algorithm generates entirely new candidates uniformly at random across the entire search domain. This helps prevent premature convergence to local optima and facilitates discovery of globally better regions.
# Exploitation mechanisms:
# 1. Incumbent-Centered Perturbation: The primary exploitation mechanism involves generating new candidates by perturbing the current `best_x` with Gaussian noise. This focuses the search on the vicinity of the best-known solution, attempting to find improvements nearby.
# 2. Greedy Selection: Only improvements are accepted, directly driving the search towards lower objective values.
# Boundary handling: All generated candidate points, whether from uniform sampling or perturbation, are explicitly clipped to ensure they remain within the `lower_bound` and `upper_bound` of the search space. `x_clipped = np.clip(x_candidate, lower_bound, upper_bound)`.
# Budget strategy: The algorithm strictly adheres to the provided `budget`. Every call to the objective function `func` increments `current_budget_used`. The optimization loop terminates as soon as `current_budget_used` reaches `budget`. If `budget` is 0, it returns a default neutral point without any evaluation. If `budget` is 1, it performs a single evaluation and returns that result.
# Closest known influences: This algorithm shares conceptual similarities with basic Random Search for its exploration phases and with simple Evolutionary Strategies (like (1+1)-ES) or hill-climbing for its exploitation via perturbation and greedy selection. The fixed probability of switching between exploration and exploitation is a common heuristic in hybrid algorithms.
# Novelty or unusual aspects: The algorithm's design is intentionally straightforward, combining well-established heuristics without introducing complex novel mechanisms. Its balance between fixed-probability uniform exploration and incumbent-centered Gaussian perturbation is a practical compromise for black-box problems where no gradient information is available.
# Failure modes:
# 1. Stagnation: If `perturbation_scale_factor` is too small, the algorithm might get stuck in local optima, especially if the `exploration_probability` is also low or if the global optimum is far from any initially sampled points.
# 2. Slow convergence: If `perturbation_scale_factor` is too large, the search might be too "jumpy" and fail to fine-tune solutions effectively, resembling more of a pure random search.
# 3. Inefficient for high dimensions: In very high-dimensional spaces, both uniform random sampling and small-step perturbations can become inefficient for finding improvements due to the curse of dimensionality.
# 4. No adaptive step size: The fixed `perturbation_scale_factor` might not be optimal throughout the search; a dynamic adaptation could improve performance.
# 5. Sensitive to parameter tuning: The performance is sensitive to `exploration_probability` and `perturbation_scale_factor`.
