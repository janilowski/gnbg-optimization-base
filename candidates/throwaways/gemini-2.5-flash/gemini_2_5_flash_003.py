import numpy as np

class Algorithm:
    """
    GNBG (Guess-and-Check for Numerical Black-box Global) minimization benchmark algorithm.

    This algorithm employs a hybrid strategy, combining initial broad exploration
    with an iterative cycle of exploitation (incumbent-centered perturbation)
    and controlled exploration (uniform random sampling).
    """

    def __init__(self, budget: int, dim: int):
        """
        Initializes the algorithm with the total evaluation budget and problem dimension.

        Args:
            budget (int): The maximum number of function evaluations allowed.
            dim (int): The dimensionality of the problem's search space.
        """
        if not isinstance(budget, int) or budget < 0:
            raise ValueError("Budget must be a non-negative integer.")
        if not isinstance(dim, int) or dim <= 0:
            raise ValueError("Dimension must be a positive integer.")

        self.budget = budget
        self.dim = dim
        self.current_budget_used = 0

    def _read_bounds(self, func):
        """
        Reads the lower and upper bounds for each dimension from the function object.
        Prioritizes `func.lower`/`func.upper`, falls back to `func.bounds.lb`/`func.bounds.ub`.

        Args:
            func: The objective function object.

        Returns:
            tuple[np.ndarray, np.ndarray]: A tuple containing (lower_bound, upper_bound)
                                           as numpy arrays of shape (self.dim,).
        Raises:
            AttributeError: If bounds cannot be found on the function object.
            ValueError: If the bounds' shape does not match the problem dimension.
        """
        lower_bound = None
        upper_bound = None

        # Try func.lower / func.upper first
        if hasattr(func, 'lower') and hasattr(func, 'upper'):
            lower_bound = np.asarray(func.lower, dtype=float)
            upper_bound = np.asarray(func.upper, dtype=float)
        # Fallback to func.bounds.lb / func.bounds.ub
        elif hasattr(func, 'bounds') and hasattr(func.bounds, 'lb') and hasattr(func.bounds, 'ub'):
            lower_bound = np.asarray(func.bounds.lb, dtype=float)
            upper_bound = np.asarray(func.bounds.ub, dtype=float)
        else:
            raise AttributeError(
                "Function object must have 'lower'/'upper' or 'bounds.lb'/'bounds.ub' attributes."
            )

        # Ensure bounds are correctly shaped for the dimension
        if lower_bound.ndim == 0:  # Scalar bound, apply to all dimensions
            lower_bound = np.full(self.dim, lower_bound)
        if upper_bound.ndim == 0:  # Scalar bound, apply to all dimensions
            upper_bound = np.full(self.dim, upper_bound)

        if lower_bound.shape != (self.dim,) or upper_bound.shape != (self.dim,):
            raise ValueError(
                f"Bounds shape mismatch. Expected ({self.dim},), "
                f"got {lower_bound.shape} and {upper_bound.shape}."
            )
            
        return lower_bound, upper_bound

    def _evaluate(self, func, x):
        """
        Evaluates the objective function for a given candidate solution 'x',
        respecting the total budget.

        Args:
            func: The objective function.
            x (np.ndarray): The candidate solution to evaluate.

        Returns:
            float: The objective value of x, or np.inf if budget is exhausted.
        """
        if self.current_budget_used >= self.budget:
            return np.inf  # Return infinity if budget is exhausted to prevent further evaluations
        
        self.current_budget_used += 1
        return func(x)

    def __call__(self, func) -> tuple[np.ndarray, float]:
        """
        Executes the optimization process to find the minimum of the given function.

        Args:
            func: The objective function to minimize. It must accept a numpy array
                  of shape (self.dim,) and return a float. It must also have
                  attributes for lower and upper bounds (e.g., `func.lower`, `func.upper`).

        Returns:
            tuple[np.ndarray, float]: A tuple containing the best found solution
                                      (best_x) and its corresponding objective value (best_y).
        """
        lower_bound, upper_bound = self._read_bounds(func)
        search_range = upper_bound - lower_bound

        best_x = None
        best_y = np.inf

        # Handle zero budget explicitly: no evaluations possible
        if self.budget == 0:
            # Return a neutral point within bounds and infinity, as no evaluations can be made.
            return lower_bound + 0.5 * search_range, np.inf

        # 1. Initialization: Evaluate at least one point to set initial best_x, best_y
        initial_x = lower_bound + np.random.rand(self.dim) * search_range
        best_x = initial_x
        best_y = self._evaluate(func, initial_x)

        # If budget was 1, we are done after the first evaluation.
        if self.current_budget_used >= self.budget:
            return best_x, best_y

        # Continue with more initial exploratory samples if budget allows.
        # This helps quickly cover the search space before focusing.
        num_initial_exploratory_samples = max(1, min(self.budget - self.current_budget_used, self.dim * 2))
        
        for _ in range(num_initial_exploratory_samples):
            if self.current_budget_used >= self.budget:
                break # Stop if budget runs out during initial sampling
            x_candidate = lower_bound + np.random.rand(self.dim) * search_range
            y_candidate = self._evaluate(func, x_candidate)
            
            if y_candidate < best_y:
                best_y = y_candidate
                best_x = x_candidate

        # 2. Main Optimization Loop: Mixed uniform exploration and incumbent-centered perturbation
        # Parameters for the algorithm's behavior
        exploration_probability = 0.15      # Probability of performing a global uniform exploration step
        perturbation_scale_factor = 0.1     # Scales the standard deviation of Gaussian perturbation relative to search range

        while self.current_budget_used < self.budget:
            x_candidate = None

            # Decide between exploration (uniform random) or exploitation (perturb incumbent)
            if np.random.rand() < exploration_probability:
                # Exploration: Generate a new candidate uniformly across the entire search space
                x_candidate = lower_bound + np.random.rand(self.dim) * search_range
            else:
                # Exploitation: Perturb the current best solution with Gaussian noise
                # The standard deviation for perturbation is proportional to the search range for each dimension.
                perturbation_std_dev = perturbation_scale_factor * search_range
                x_candidate = best_x + np.random.normal(loc=0, scale=perturbation_std_dev, size=self.dim)
                
                # Boundary handling: Clip the perturbed candidate to ensure it stays within bounds
                x_candidate = np.clip(x_candidate, lower_bound, upper_bound)
            
            # Evaluate the new candidate
            y_candidate = self._evaluate(func, x_candidate)

            # Update the best found solution if the new candidate is better
            if y_candidate < best_y:
                best_y = y_candidate
                best_x = x_candidate
        
        return best_x, best_y
