# Summary: This algorithm implements a variant of restart hill climbing using coordinate masks for perturbation. It repeatedly initializes at random points in the search space and then performs a local search. The local search perturbs a randomly chosen subset of dimensions (a "mask") using Gaussian noise. If an improvement is found, the current solution is updated; otherwise, an unsuccessful step counter increments. Once a maximum number of unsuccessful steps is reached, the local search terminates, and a new random restart point is chosen (if budget allows). The best solution found across all restarts and local searches is maintained and returned.
# Search state: The primary search state consists of the `best_x` (the best solution found globally) and `best_y` (its objective value). During a local search phase, `current_x` and `current_y` represent the current best solution within that particular hill climbing run. The algorithm also tracks the remaining `budget`.
# Candidate generation: Candidates are generated by perturbing `current_x`. A random subset of dimensions (a "coordinate mask") is chosen. For these masked dimensions, Gaussian noise scaled by the dimension's search range is added. Dimensions not in the mask remain unchanged.
# Selection and replacement: In the local search phase, a candidate `candidate_x` is generated from `current_x`. If `candidate_y` (the objective value of `candidate_x`) is strictly better than `current_y`, then `candidate_x` replaces `current_x`. If `current_y` (the new local best) is better than `best_y`, then `best_x` and `best_y` are updated.
# Adaptation: The algorithm does not have explicit online adaptation of parameters like step size or mask size during a run. The perturbation scale factor is static but scales relative to the problem's bounds. The local search implicitly adapts by stopping after `hc_max_unsuccessful_steps`, effectively shifting focus or restarting if no immediate improvements are found, which can be seen as an adaptive restart mechanism.
# Exploration mechanisms:
# - Random Restarts: The algorithm frequently restarts the local search from a new, randomly sampled point within the entire search space. This helps escape local optima and explore different regions.
# - Coordinate Masks: By randomly selecting subsets of dimensions to perturb, the algorithm explores directions that are not strictly axis-aligned (as in simple coordinate ascent/descent) but also not completely random in all dimensions simultaneously. This balances focused movement with directional diversity.
# Exploitation mechanisms:
# - Hill Climbing: The core local search mechanism is greedy hill climbing. It always moves towards improved solutions.
# - Step Size: The Gaussian perturbation with a fixed standard deviation (relative to the search range) allows for fine-tuning movements in promising areas, leveraging the local gradient information implicitly.
# Boundary handling: When generating candidate points, `numpy.clip` is used to ensure that all coordinate values remain within the `lower_bound` and `upper_bound` of the search space. This handles boundaries by projecting points back onto the feasible region.
# Budget strategy: The budget is strictly managed. Each call to `func` decrements the internal budget counter. All loops and operations check `self.budget > 0` to ensure no evaluations occur beyond the allotted budget. The algorithm stops immediately once the budget is exhausted.
# Closest known influences: This algorithm draws inspiration from:
# - Random Restart Hill Climbing (RRHC): The overall meta-strategy of restarting local searches from new random points.
# - Stochastic Local Search: Generally falls under this category due to the use of randomness in candidate generation.
# Novelty or unusual aspects: The specific combination of random restarts with a coordinate-masked Gaussian perturbation strategy within the local search phase. The `max_mask_size` being `dim // 2` is a heuristic choice balancing exploration of subspaces versus single-dimension changes, particularly effective for dimensions greater than 3.
# Failure modes:
# - Premature convergence: If `hc_max_unsuccessful_steps` is too high, it might spend too much time in a poor local optimum, reducing the number of restarts and overall exploration.
# - Insufficient exploitation: If `perturbation_scale_factor` is too large or `hc_max_unsuccessful_steps` is too low, the local search might be too "jumpy" or too short-lived to properly converge to local optima.
# - Suboptimal hyperparameter tuning: The fixed hyperparameters might not be optimal for all problem types or dimensions, as they are not adaptive.
# - High dimensionality: In very high dimensions, randomly sampling an effective coordinate mask might become less efficient, and `dim // 2` might still be too large a mask size for effective local search without more sophisticated step size adaptation.
