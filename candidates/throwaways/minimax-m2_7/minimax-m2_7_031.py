import numpy as np


def _extract_bounds(func):
    """Extract lower and upper bounds from a function object.

    Supports two common conventions:
        func.lower / func.upper   (scalars or arrays)
        func.bounds.lb / func.bounds.ub   (objects with .lb and .ub)

    Returns
    -------
    lower, upper : numpy.ndarray
        Column vectors containing the lower and upper bounds.
    """
    if hasattr(func, 'lower') and hasattr(func, 'upper'):
        lower = np.asarray(func.lower)
        upper = np.asarray(func.upper)
    elif hasattr(func, 'bounds'):
        lower = np.asarray(func.bounds.lb)
        upper = np.asarray(func.bounds.ub)
    else:
        raise ValueError("Cannot determine bounds of the function. "
                         "Expected attributes 'lower'/'upper' or 'bounds.lb'/'bounds.ub'.")
    # Ensure 1‑D arrays
    if lower.ndim == 0:
        lower = np.atleast_1d(lower)
        upper = np.atleast_1d(upper)
    return lower, upper


class Algorithm:
    """Simple (1+1)-ES with adaptive step size for bound‑constrained minimization.

    Parameters
    ----------
    budget : int
        Maximum number of function evaluations allowed.
    dim : int
        Dimensionality of the problem (number of decision variables).
    """

    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

        # Internal state (will be set in __call__)
        self.current_x = None
        self.current_y = None
        self.best_x = None
        self.best_y = None
        self.evaluations = 0

        # Step size vector (one entry per dimension)
        self.step_size = None

        # Adaptation counters
        self.success_count = 0
        self.failure_count = 0
        self.adapt_every = None

    def __call__(self, func):
        """Run the optimizer and return (best_x, best_y)."""
        # ------------------------------------------------------------------
        # Guard against zero budget
        if self.budget <= 0:
            # Return any feasible point with infinite objective
            lower, upper = _extract_bounds(func)
            lower = np.asarray(lower, dtype=float)
            upper = np.asarray(upper, dtype=float)
            if lower.shape[0] != self.dim:
                if lower.shape[0] == 1:
                    lower = np.full(self.dim, lower[0])
                    upper = np.full(self.dim, upper[0])
                else:
                    raise ValueError("Dimension mismatch between bounds and specified dim.")
            return lower, np.inf

        # ------------------------------------------------------------------
        # Extract and validate bounds
        lower, upper = _extract_bounds(func)
        if lower.shape[0] != self.dim:
            if lower.shape[0] == 1 and self.dim > 1:
                # Expand scalar bounds to full dimensionality
                lower = np.full(self.dim, lower[0], dtype=float)
                upper = np.full(self.dim, upper[0], dtype=float)
            else:
                raise ValueError("Dimension of bounds does not match specified dim.")
        else:
            lower = lower.astype(float)
            upper = upper.astype(float)

        # ------------------------------------------------------------------
        # Initialise step size (per dimension) and adaptation parameters
        range_per_dim = upper - lower
        self.step_size = range_per_dim / 5.0
        self.adapt_every = max(10, self.dim * 10)

        # ------------------------------------------------------------------
        # Initial random solution
        self.current_x = lower + np.random.rand(self.dim) * range_per_dim
        self.current_y = func(self.current_x)
        self.evaluations = 1
        self.best_x = self.current_x.copy()
        self.best_y = self.current_y

        # ------------------------------------------------------------------
        # Main optimisation loop (1+1)-ES
        while self.evaluations < self.budget:
            # Generate candidate by Gaussian perturbation
            candidate_x = self.current_x + self.step_size * np.random.randn(self.dim)
            candidate_x = np.clip(candidate_x, lower, upper)

            # Evaluate candidate
            candidate_y = func(candidate_x)
            self.evaluations += 1

            # Selection and replacement
            if candidate_y <= self.current_y:
                self.current_x = candidate_x
                self.current_y = candidate_y
                self.success_count += 1
                if candidate_y <= self.best_y:
                    self.best_x = candidate_x.copy()
                    self.best_y = candidate_y
            else:
                self.failure_count += 1

            # ------------------------------------------------------------------
            # Adaptation of step size using the 1/5 success rule
            if self.evaluations % self.adapt_every == 0:
                total = self.success_count + self.failure_count
                if total > 0:
                    success_rate = self.success_count / total
                    if success_rate > 0.2:
                        self.step_size *= 1.2
                    else:
                        self.step_size *= 0.8

                # Reset counters
                self.success_count = 0
                self.failure_count = 0

                # Keep step size within reasonable bounds
                min_step = range_per_dim / 1e6
                max_step = range_per_dim * 2
                self.step_size = np.clip(self.step_size, min_step, max_step)

                # Restart if step size becomes negligible
                if np.all(self.step_size < min_step * 10):
                    if self.evaluations < self.budget:
                        # Re‑initialise to a new random point
                        self.current_x = lower + np.random.rand(self.dim) * range_per_dim
                        self.current_y = func(self.current_x)
                        self.evaluations += 1
                        if self.current_y <= self.best_y:
                            self.best_x = self.current_x.copy()
                            self.best_y = self.current_y
                    # If we have exhausted the budget during restart, exit
                    if self.evaluations >= self.budget:
                        break

        return self.best_x, self.best_y
