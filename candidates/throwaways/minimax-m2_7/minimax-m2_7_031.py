# Summary: A simple (1+1) Evolution Strategy with an adaptive step size (1/5 rule) for bound-constrained black-box minimization. The algorithm starts with a random solution, then iteratively mutates it using Gaussian perturbations scaled by a step vector. If a mutant improves the current objective it is accepted; otherwise it is discarded. The step size is periodically adjusted based on the recent success rate, and the algorithm restarts from a new random point when the step size becomes too small relative to the search range.
# Search state: The optimizer maintains the current solution (vector), its objective value, the best solution found so far, the number of evaluations performed, the current step size vector (one per dimension), and counters for successes and failures used for adaptation.
# Candidate generation: A new candidate is generated by adding independent Gaussian noise to the current solution. The noise standard deviation in each dimension equals the corresponding entry of the step size vector, which is then clipped to the problem’s bounds.
# Selection and replacement: The candidate replaces the current solution only if its objective value is less than or equal to that of the current solution (minimization). The global best solution is updated whenever a better objective is encountered.
# Adaptation: Every adapt_every evaluations (at least 10 or dim*10) the algorithm computes the success rate (proportion of improvements). If the rate exceeds 0.2 the step size is multiplied by 1.2 (exploration), otherwise it is multiplied by 0.8 (exploitation). The step size is also clamped between a tiny fraction and twice the bound range to avoid runaway values.
# Exploration mechanisms: A relatively large initial step size (≈1/5 of the bound range) encourages broad sampling. Random restarts occur when the step size becomes too small, reinitializing the current solution to a fresh random point within the bounds.
# Exploitation mechanisms: As the algorithm discovers improvements, the success‑based adaptation reduces the step size, focusing the search around the current best region. Clipping to bounds prevents stepping outside the feasible region.
# Boundary handling: All candidate vectors are clipped component‑wise to the provided lower and upper bounds. If the function object supplies scalar bounds they are expanded to match the problem dimension.
# Budget strategy: The total number of function evaluations is strictly limited by the budget argument. The algorithm evaluates exactly one solution per iteration, checks the counter after each evaluation, and aborts before any extra evaluation that would exceed the budget. Any restart evaluations are also gated by the remaining budget.
# Closest known influences: The implementation is closely related to the classic (1+1) Evolution Strategy with the 1/5 success rule and to simple random search methods. It also shares ideas with re‑initialization strategies used in hybrid local search.
# Novelty or unusual aspects: The use of per‑dimension step sizes (rather than a single global sigma) combined with a simple restart trigger offers a balance between simplicity and robustness. The code is compact and relies only on NumPy and the standard library, making it easy to embed in any benchmark harness.
# Failure modes: The algorithm may become trapped in local optima, especially on rugged or highly multi‑modal landscapes. Its performance degrades in very high dimensions or when the objective is heavily stochastic, because the success‑rate adaptation can misinterpret noise. The restart mechanism mitigates some stagnation but cannot guarantee global convergence.
